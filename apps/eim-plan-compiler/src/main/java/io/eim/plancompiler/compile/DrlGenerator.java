package io.eim.plancompiler.compile;

import io.eim.plancompiler.model.PlanModel;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Forward-chaining DRL generation (arch §5.1): one rule per component with
 * compiler-controlled salience from the topological order (deps fire first,
 * NFR-08 determinism), plus backward-chaining query definitions powering
 * dispute-triage pre-tagging (FR-704.1). All arithmetic routes through the
 * generated DECIMAL128 helper — no doubles anywhere.
 */
public final class DrlGenerator {

    public static String generate(PlanModel plan, List<String> topo) {
        StringBuilder drl = new StringBuilder();
        drl.append("// Generated by eim-plan-compiler — DO NOT EDIT.\n")
                .append("// Forward-chaining rules with deterministic salience +\n")
                .append("// backward-chaining triage queries.\n")
                .append("package eim.rules;\n\n")
                .append("global org.slf4j.Logger log;\n\n")
                .append("query \"triageCategory\" (String $payee, String $category)\n")
                .append("    Triage( payee == $payee, category == $category )\n")
                .append("end\n\n");

        int n = topo.size();
        for (int i = 0; i < n; i++) {
            String name = topo.get(i);
            PlanModel.Component c = plan.component(name);
            if (c == null) {
                continue;
            }
            int salience = 1000 - i;
            Set<String> deps = depsOf(c);
            if (c.kind() == PlanModel.Kind.TIER_TABLE) {
                appendTierRule(drl, c, salience, deps);
            } else if (c.formula() != null && !c.formula().isBlank()) {
                appendFormulaRule(drl, c, salience, deps);
            }
            appendProtectionRule(drl, c, 400 + n - i, deps);
        }
        appendTriageRules(drl);
        return drl.toString();
    }

    private static Set<String> depsOf(PlanModel.Component c) {
        Set<String> deps = new LinkedHashSet<>();
        if (c.dependsOn() != null) {
            deps.addAll(c.dependsOn());
        }
        if (c.formula() != null) {
            for (String token : c.formula().split("[^A-Za-z0-9_@]+")) {
                if (token.startsWith("@") && token.length() > 1) {
                    deps.add(token.substring(1));
                }
            }
        }
        return deps;
    }

    private static void appendFormulaRule(StringBuilder drl, PlanModel.Component c,
                                          int salience, Set<String> deps) {
        List<String> bindings = new ArrayList<>();
        String expr = translate(c.formula(), deps, bindings);
        drl.append("rule \"calc_").append(c.name()).append("\"\n")
                .append("salience ").append(salience).append("\n")
                .append("no-loop true\nwhen\n")
                .append("    $in : Inputs( payee != null )\n");
        int i = 1;
        for (String dep : deps) {
            drl.append("    Fact( component == \"").append(dep)
                    .append("\", payee == $in.payee, $d").append(i).append(" : value )\n");
            i++;
        }
        drl.append("then\n");
        if (c.outputType() == PlanModel.OutputType.BOOLEAN) {
            drl.append("    insertLogical( new Flag( $in.getPayee(), \"").append(c.name())
                    .append("\", ").append(expr).append(") );\n");
        } else {
            drl.append("    insertLogical( new Fact( \"").append(c.name())
                    .append("\", $in.getPayee(), ").append(expr).append(", \"")
                    .append(c.outputType()).append("\") );\n");
        }
        drl.append("end\n\n");
    }

    private static void appendTierRule(StringBuilder drl, PlanModel.Component c,
                                       int salience, Set<String> deps) {
        String basisDep = deps.isEmpty() ? null : deps.iterator().next();
        drl.append("rule \"calc_").append(c.name()).append("\"\n")
                .append("salience ").append(salience).append("\n")
                .append("no-loop true\nwhen\n")
                .append("    $in : Inputs( payee != null )\n");
        String basis;
        if (basisDep != null) {
            drl.append("    Fact( component == \"").append(basisDep)
                    .append("\", payee == $in.payee, $d1 : value )\n");
            basis = "$d1";
        } else {
            basis = "$in.num(\"booked_amount\")";
        }
        drl.append("then\n")
                .append("    insertLogical( new Fact( \"").append(c.name())
                .append("\", $in.getPayee(), Tiers.slice_").append(c.name())
                .append("($in.fromOrZero(\"window_from\"), ").append(basis)
                .append("), \"CURRENCY\") );\n")
                .append("end\n\n");
    }

    /** Protection eligibility (FR-405): numeric enforcement lives in the
     *  calc engine; these rules expose eligibility flags to orchestration. */
    private static void appendProtectionRule(StringBuilder drl, PlanModel.Component c,
                                             int salience, Set<String> deps) {
        PlanModel.Protections pr = c.protections();
        if (pr == null) {
            return;
        }
        String kind = pr.clawbackWindowDays() != null ? "CLAWBACK"
                : pr.capValue() != null ? "CAP"
                : pr.drawKind() != null ? "DRAW" : null;
        if (kind == null) {
            return;
        }
        drl.append("rule \"protection_").append(c.name()).append("\"\n")
                .append("salience ").append(salience).append("\n")
                .append("no-loop true\nwhen\n")
                .append("    $in : Inputs( payee != null )\n");
        if (!deps.isEmpty()) {
            drl.append("    Fact( component == \"").append(deps.iterator().next())
                    .append("\", payee == $in.payee )\n");
        }
        drl.append("then\n")
                .append("    insertLogical( new Flag( $in.getPayee(), \"").append(kind)
                .append("\", true) );\n")
                .append("end\n\n");
    }

    private static void appendTriageRules(StringBuilder drl) {
        // Symptom -> category inference (FR-704.1): forward rules feed the
        // backward query above; the default catches anything unmapped.
        drl.append("rule \"triage_source_data\"\nsalience 20\nno-loop true\nwhen\n")
                .append("    Dispute( symptom in ( \"late_arrival\", \"missing_source_row\", \"currency_mismatch\" ), $p : payee )\n")
                .append("then\n")
                .append("    insertLogical( new Triage( $p, \"SOURCE_DATA\" ) );\nend\n\n")
                .append("rule \"triage_credit_split\"\nsalience 20\nno-loop true\nwhen\n")
                .append("    Dispute( symptom == \"split_sum_off\", $p : payee )\n")
                .append("then\n")
                .append("    insertLogical( new Triage( $p, \"CREDIT_SPLIT\" ) );\nend\n\n")
                .append("rule \"triage_window_state\"\nsalience 20\nno-loop true\nwhen\n")
                .append("    Dispute( symptom in ( \"window_boundary\", \"reset_cadence\" ), $p : payee )\n")
                .append("then\n")
                .append("    insertLogical( new Triage( $p, \"WINDOW_STATE\" ) );\nend\n\n")
                .append("rule \"triage_default_plan_logic\"\nsalience 1\nno-loop true\nwhen\n")
                .append("    Dispute( $p : payee )\n")
                .append("then\n")
                .append("    insertLogical( new Triage( $p, \"PLAN_LOGIC\" ) );\nend\n");
    }

    /** Formula -> Java expression over Calc helpers; dep refs become $dN. */
    static String translate(String formula, Set<String> deps, List<String> bindings) {
        StringBuilder out = new StringBuilder();
        int i = 0;
        while (i < formula.length()) {
            char ch = formula.charAt(i);
            if (Character.isWhitespace(ch)) {
                i++;
                continue;
            }
            if (ch == '@' || ch == '$') {
                int j = i + 1;
                while (j < formula.length()
                        && (Character.isLetterOrDigit(formula.charAt(j)) || formula.charAt(j) == '_')) {
                    j++;
                }
                String name = formula.substring(i + 1, j);
                if (ch == '@') {
                    int idx = new ArrayList<>(deps).indexOf(name) + 1;
                    out.append("$d").append(idx);
                } else if (name.equals("period_start") || name.equals("period_end")) {
                    out.append("$in.raw(\"").append(name).append("\")");
                } else {
                    out.append("$in.num(\"").append(name).append("\")");
                }
                i = j;
                continue;
            }
            if (Character.isDigit(ch) || ch == '.') {
                int j = i;
                while (j < formula.length()
                        && (Character.isDigit(formula.charAt(j)) || formula.charAt(j) == '.')) {
                    j++;
                }
                out.append("Calc.v(\"").append(formula, i, j).append("\")");
                i = j;
                continue;
            }
            if (Character.isLetter(ch)) {
                int j = i;
                while (j < formula.length()
                        && (Character.isLetterOrDigit(formula.charAt(j)) || formula.charAt(j) == '_')) {
                    j++;
                }
                String fn = formula.substring(i, j).toLowerCase(java.util.Locale.ROOT);
                out.append("Calc.").append(fn);
                i = j;
                continue;
            }
            switch (ch) {
                case '+' -> out.append("Calc.add");
                case '-' -> out.append("Calc.sub");
                case '*' -> out.append("Calc.mul");
                case '/' -> out.append("Calc.div");
                case '<' -> out.append("Calc.lt");
                case '>' -> out.append("Calc.gt");
                case '(' -> out.append('(');
                case ')' -> out.append(')');
                case ',' -> out.append(',');
                default -> throw new IllegalArgumentException(
                        "unsupported character in formula: " + ch);
            }
            i++;
        }
        return out.toString();
    }

    private DrlGenerator() {
    }
}
