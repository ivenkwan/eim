package io.eim.plancompiler.compile;

import io.eim.plancompiler.model.PlanModel;

import java.util.List;

/**
 * DMN generation for tier tables (arch §5.2): each TIER_TABLE component
 * becomes a decision mapping the basis amount to the applicable bracket
 * RATE (the config decision — the numeric slicing itself stays in the calc
 * service per the hybrid-engine mandate AD-1). Brackets are half-open
 * {@code [prev..upTo]} intervals plus a catch-all row, hit policy UNIQUE.
 * Emits DMN 1.2 (kie-dmn's fully-supported dialect) with FEEL {@code number}
 * types and an explicit inputData node so the FEEL compiler resolves
 * {@code amount}.
 */
final class DmnGenerator {

    public static String generate(PlanModel plan) {
        StringBuilder x = new StringBuilder();
        x.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
                .append("<!-- Generated by eim-plan-compiler — DO NOT EDIT. -->\n")
                .append("<definitions xmlns=\"http://www.omg.org/spec/DMN/20180521/MODEL/\" ")
                .append("id=\"eim-plan-tiers\" name=\"eim-plan-tiers\" ")
                .append("namespace=\"https://eim.io/plan/tiers\">\n");
        for (PlanModel.Component c : plan.components() == null ? List.<PlanModel.Component>of()
                : plan.components()) {
            if (c.kind() == PlanModel.Kind.TIER_TABLE && c.tiers() != null
                    && c.tiers().brackets() != null && !c.tiers().brackets().isEmpty()) {
                appendDecision(x, c);
            }
        }
        x.append("</definitions>\n");
        return x.toString();
    }

    private static void appendDecision(StringBuilder x, PlanModel.Component c) {
        String id = c.name() + "_rate";
        StringBuilder rows = new StringBuilder();
        String prev = null;
        int i = 0;
        for (PlanModel.Bracket b : c.tiers().brackets()) {
            String cell;
            if (b.upTo() == null) {
                // catch-all as an explicit OPEN interval keeps the table
                // disjoint under the UNIQUE hit policy
                cell = prev == null ? ">= 0" : "> " + prev;
            } else if (prev == null) {
                cell = "[0.." + b.upTo() + "]";
            } else {
                cell = "(" + prev + ".." + b.upTo() + "]";
            }
            rows.append("        <rule id=\"").append(id).append("_r").append(i).append("\">\n")
                    .append("          <inputEntry id=\"").append(id).append("_r").append(i).append("i1\">\n")
                    .append("            <text>").append(cell).append("</text>\n")
                    .append("          </inputEntry>\n")
                    .append("          <outputEntry id=\"").append(id).append("_r").append(i).append("o1\">\n")
                    .append("            <text>").append(b.rate()).append("</text>\n")
                    .append("          </outputEntry>\n")
                    .append("        </rule>\n");
            prev = b.upTo();
            i++;
        }
        x.append("  <inputData id=\"").append(id).append("_amount\" name=\"amount\">\n")
                .append("    <variable name=\"amount\" typeRef=\"number\"/>\n")
                .append("  </inputData>\n")
                .append("  <decision id=\"").append(id).append("\" name=\"").append(id).append("\">\n")
                .append("    <variable name=\"").append(id).append("\" typeRef=\"number\"/>\n")
                .append("    <informationRequirement>\n")
                .append("      <requiredInput href=\"#").append(id).append("_amount\"/>\n")
                .append("    </informationRequirement>\n")
                .append("    <decisionTable id=\"").append(id).append("_table\" hitPolicy=\"UNIQUE\" ")
                .append("preferredOrientation=\"Rule-as-Row\">\n")
                .append("      <input id=\"").append(id).append("_i1\">\n")
                .append("        <inputExpression id=\"").append(id).append("_i1_ie\" typeRef=\"number\">\n")
                .append("          <text>amount</text>\n")
                .append("        </inputExpression>\n")
                .append("      </input>\n")
                .append("      <output id=\"").append(id).append("_o1\" name=\"rate\" ")
                .append("typeRef=\"number\"/>\n")
                .append(rows)
                .append("    </decisionTable>\n")
                .append("  </decision>\n");
    }

    private DmnGenerator() {
    }
}
